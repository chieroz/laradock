#!/usr/bin/env bash
# Local HTTPS between the apps of this Laradock setup.
#
# Generates docker-compose.local.yml (gitignored) so that, inside the stack:
#   - every server_name in nginx/sites/*.conf resolves to nginx (network aliases on frontend + backend;
#     Docker's DNS has no wildcards, hence one alias per site);
#   - the PHP containers (workspace*, php-fpm*) trust the mkcert root CA that signed nginx/ssl/default.crt,
#     so an app calls another at https://<site>.test with certificate verification on.
# It also adds the file to COMPOSE_FILE and sets MKCERT_CAROOT in .env, and warns about site names the
# certificate doesn't cover.
#
# Run it after adding or renaming a vhost, then: docker compose up -d nginx <the PHP services it lists>
# Requires mkcert (brew install mkcert && mkcert -install). The why, the certificate, the setups: LOCAL-HTTPS.md
set -euo pipefail
cd "$(dirname "$0")"

OUT=docker-compose.local.yml
ENV_FILE=.env
CERT=nginx/ssl/default.crt
CA_TARGET=/usr/local/share/ca-certificates/mkcert-rootCA.crt

die() { echo "local-https: $*" >&2; exit 1; }
env_get() { sed -nE "s/^$1=\"?([^\"]*)\"?[[:space:]]*$/\1/p" "$ENV_FILE" | tail -1; }

[ -f "$ENV_FILE" ] || die "no $ENV_FILE here (copy .env.example first)"
command -v mkcert >/dev/null || die "mkcert not found (brew install mkcert && mkcert -install)"

# --- site names -------------------------------------------------------------------------------------
# Uncommented server_name lines only; *.example files are skipped by the glob.
all_names=$(sed -nE 's/^[[:space:]]*server_name[[:space:]]+([^;]+);.*/\1/p' nginx/sites/*.conf \
  | tr ' \t' '\n\n' | grep -v '^$' | sort -u)
names=$(printf '%s\n' "$all_names" | grep -vE '^(localhost|_)$|[*~]' || true)
skipped=$(printf '%s\n' "$all_names" | grep -E '[*~]' || true)
[ -n "$names" ] || die "no server_name found in nginx/sites/*.conf"
set -f  # from here on, wildcard SANs like *.edt.test are plain strings, never globs

# --- mkcert CA ----------------------------------------------------------------------------------------
caroot=$(env_get MKCERT_CAROOT)
if [ -z "$caroot" ]; then
  caroot=$(mkcert -CAROOT)
  printf '\n# mkcert -CAROOT: docker-compose.local.yml mounts its rootCA.pem into the PHP containers\nMKCERT_CAROOT="%s"\n' \
    "$caroot" >> "$ENV_FILE"
  echo "added MKCERT_CAROOT to $ENV_FILE"
fi
[ -f "$caroot/rootCA.pem" ] || die "$caroot/rootCA.pem not found (run: mkcert -install)"

# --- COMPOSE_FILE -------------------------------------------------------------------------------------
sep=$(env_get COMPOSE_PATH_SEPARATOR); sep=${sep:-:}
compose_file=$(env_get COMPOSE_FILE); compose_file=${compose_file:-docker-compose.yml}
# The base stack without our file, to list its services before (re)generating it.
base=$(printf '%s\n' "$compose_file" | tr "$sep" '\n' | grep -vx "$OUT" | paste -sd "$sep" -)

services=$(COMPOSE_FILE="$base" COMPOSE_PATH_SEPARATOR="$sep" docker compose config --services)
printf '%s\n' "$services" | grep -qx nginx || die "no nginx service in $base"
php_services=$(printf '%s\n' "$services" | grep -E '^(workspace|php-fpm)([-_]?[0-9]+)?$' | sort)

# --- write docker-compose.local.yml -----------------------------------------------------------------
{
  echo "# Generated by ./local-https.sh from nginx/sites/*.conf: don't edit, re-run the script."
  echo "x-site-aliases: &site-aliases"
  printf '%s\n' "$names" | sed 's/^/  - /'
  echo
  echo "x-mkcert-ca: &mkcert-ca"
  echo "  type: bind"
  echo "  source: \${MKCERT_CAROOT}/rootCA.pem"
  echo "  target: $CA_TARGET"
  echo "  read_only: true"
  echo
  echo "services:"
  echo "  nginx:"
  echo "    networks:"
  echo "      frontend:"
  echo "        aliases: *site-aliases"
  echo "      backend:"
  echo "        aliases: *site-aliases"
  for s in $php_services; do
    # The CA is a bind mount, so it can't be baked into the image: refresh the trust store at each start.
    case $s in
      workspace*) start=/sbin/my_init ;;
      *) start=php-fpm ;;
    esac
    echo
    echo "  $s:"
    echo "    volumes:"
    echo "      - *mkcert-ca"
    echo "    command: [\"sh\", \"-c\", \"update-ca-certificates >/dev/null && exec $start\"]"
  done
} > "$OUT"

if ! printf '%s\n' "$compose_file" | tr "$sep" '\n' | grep -qx "$OUT"; then
  if grep -q '^COMPOSE_FILE=' "$ENV_FILE"; then
    sed -i.bak "s#^COMPOSE_FILE=.*#COMPOSE_FILE=${compose_file}${sep}${OUT}#" "$ENV_FILE" && rm -f "$ENV_FILE.bak"
  else
    printf '\nCOMPOSE_FILE=%s%s%s\n' "$compose_file" "$sep" "$OUT" >> "$ENV_FILE"
  fi
  echo "added $OUT to COMPOSE_FILE in $ENV_FILE"
fi

docker compose config -q || die "the generated $OUT doesn't validate"

# --- certificate coverage -----------------------------------------------------------------------------
missing=""
if [ -f "$CERT" ]; then
  sans=$(openssl x509 -in "$CERT" -noout -ext subjectAltName 2>/dev/null | tr ',' '\n' | sed -nE 's/^[[:space:]]*DNS:(.*)$/\1/p')
  for n in $names; do
    # exact match, or a wildcard one label deep (*.edt.test covers a.edt.test, not a.b.edt.test)
    printf '%s\n' "$sans" | grep -qxF -e "$n" -e "*.${n#*.}" || missing="$missing $n"
  done
else
  sans=""
  missing=" $(printf '%s ' $names)"
fi

# --- report -------------------------------------------------------------------------------------------
echo "wrote $OUT: $(printf '%s\n' "$names" | wc -l | tr -d ' ') site aliases on nginx, CA in: $(printf '%s ' $php_services)"
[ -z "$skipped" ] || echo "skipped (wildcard/regex server_name, can't be a Docker alias): $(printf '%s ' $skipped)"
if [ -n "$missing" ]; then
  echo
  echo "WARNING: $CERT doesn't cover:$missing"
  echo "reissue it (same mkcert CA, so the browser keeps trusting it), then restart nginx:"
  echo "  (cd nginx/ssl && mkcert -cert-file default.crt -key-file default.key $(printf "'%s' " $sans $missing))"
fi
echo
echo "apply with: docker compose up -d nginx $(printf '%s ' $php_services)"
